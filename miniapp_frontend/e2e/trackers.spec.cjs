'use strict'
const { test, expect } = require('@playwright/test')
const { useLocalMiniApp } = require('./helpers/local-api.cjs')

test('сон: уснул → проснулся, два события сохраняются в истории', async ({ page }) => {
  const api = await useLocalMiniApp(page)
  await page.goto('/?screen=sleep-tracker')
  await expect(page.locator('#sleepTrackerScreen')).toBeVisible()
  await page.locator('#sleepStartBtn').click()
  await expect(page.locator('#sleepActionMsg')).toContainText('малыш уснул')
  await expect(page.locator('#sleepEntries')).toContainText('уснул')
  await page.locator('#sleepEndBtn').click()
  await expect(page.locator('#sleepActionMsg')).toContainText('малыш проснулся')
  await expect(page.locator('#sleepEntries')).toContainText('проснулся')
  const posts = api.state.calls.filter((c) => c.method === 'POST')
  expect(posts.map((c) => c.body)).toEqual([{ action: 'start' }, { action: 'end' }])
  expect(api.state.history).toHaveLength(2)
  api.assertSafe()
})

test('питание: проверка пустого времени и сохранение корректного кормления', async ({ page }) => {
  const api = await useLocalMiniApp(page)
  await page.goto('/?screen=feeding-tracker')
  await expect(page.locator('#feedingTrackerScreen')).toBeVisible()
  await page.locator('[data-feed-side="left"]').click()
  await page.locator('#feedSaveBtn').click()
  await expect(page.locator('#feedingSideBody')).toContainText('Введи количество минут')
  expect(api.state.calls.filter((c) => c.method === 'POST')).toHaveLength(0)

  await page.locator('#feedDurationInput').fill('12')
  await page.locator('#feedSaveBtn').click()
  await expect(page.locator('#feedingSideBody')).toContainText('Кормление записано')
  await expect(page.locator('#feedingEntries')).toContainText('left: 12 мин')
  const posts = api.state.calls.filter((c) => c.method === 'POST')
  expect(posts.map((c) => [c.path, c.body])).toEqual([['/feeding/log', { side: 'left', duration: 12 }]])
  api.assertSafe()
})

